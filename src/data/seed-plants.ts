export function getSeedPlantByName(name: string): PlantReference | undefined {
  return seedPlants.find(p => p.name.toLowerCase() === name.toLowerCase());
}

export function searchSeedPlants(query: string): PlantReference[] {
  const q = query.toLowerCase();
  return seedPlants.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.companions.some(c => c.toLowerCase().includes(q))
  );
}

export function getSeedPlantsByMethod(method: GrowingMethod): PlantReference[] {
  return seedPlants.filter(p => p.methods.includes(method));
}

export function getPopularSeedPlants(): PlantReference[] {
  return seedPlants.slice(0, 12);
}
