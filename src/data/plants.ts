export function getPlantByName(name: string): PlantReference | undefined {
  return plantDatabase.find(
    (p) => p.name.toLowerCase() === name.toLowerCase()
  );
}

export function searchPlants(query: string): PlantReference[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return plantDatabase.filter((p) => p.name.toLowerCase().includes(q));
}

export function getPlantsByMethod(method: GrowingMethod): PlantReference[] {
  return plantDatabase.filter((p) => p.methods.includes(method));
}

export function getPopularPlants(): PlantReference[] {
  const popular = [
    'Tomato', 'Lettuce', 'Thai Basil', 'Cucumber', 'Spinach',
    'Bell Pepper', 'Mint', 'Coriander', 'Strawberry', 'Kale',
    'Broccoli', 'Carrot', 'Onion', 'Garlic', 'Lemongrass',
  ];
  return popular
    .map((name) => getPlantByName(name))
    .filter((p): p is PlantReference => p !== undefined);
}
